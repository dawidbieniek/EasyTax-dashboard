$assets = Get-Content $assetsPath -Raw | ConvertFrom-Json
$targetName = $assets.targets.PSObject.Properties.Name | Where-Object { $_ -like '*win-x64*' } | Select-Object -First 1
$target = $assets.targets.$targetName

# Packages that put files into the app (managed code, native code or resources).
$shipped = foreach ($entry in $target.PSObject.Properties) {
    $package = $entry.Value
    if ($package.type -ne 'package') { continue }

    $hasFiles = $package.PSObject.Properties.Name | Where-Object { $_ -in 'runtime', 'native', 'runtimeTargets', 'resource' }
    if (-not $hasFiles) { continue }

    $id, $version = $entry.Name -split '/'
    $nuspecPath = Join-Path $packages "$($id.ToLowerInvariant())/$version/$($id.ToLowerInvariant()).nuspec"
    if (-not (Test-Path $nuspecPath)) { continue }

    [xml]$nuspec = Get-Content $nuspecPath -Raw
    $meta = $nuspec.package.metadata
    $licenseNode = $meta.license

    $licenseId = ''
    $licenseFile = ''
    if ($licenseNode -and $licenseNode.type -eq 'expression') {
        $licenseId = $licenseNode.'#text'
    }
    elseif ($licenseNode -and $licenseNode.type -eq 'file') {
        $licenseFile = Join-Path (Split-Path $nuspecPath) $licenseNode.'#text'
        $licenseId = 'File: ' + (Get-FileHash $licenseFile -Algorithm SHA256).Hash.Substring(0, 12)
    }

    [pscustomobject]@{
        Id          = $id
        Version     = $version
        Copyright   = [string]$meta.copyright
        Authors     = [string]$meta.authors
        Url         = [string]$meta.projectUrl
        LicenseId   = $licenseId
        LicenseFile = $licenseFile
    }
}

$shipped = $shipped | Sort-Object Id
$text = New-Object System.Text.StringBuilder

[void]$text.AppendLine('EasyTax uses the open-source and third-party components listed below.')
[void]$text.AppendLine('Their licence texts follow the list. This file is generated by tools/Update-ThirdPartyNotices.ps1.')
[void]$text.AppendLine()
[void]$text.AppendLine('=== Components ===')
[void]$text.AppendLine()

[void]$text.AppendLine('.NET runtime and libraries')
[void]$text.AppendLine('  Copyright (c) .NET Foundation and Contributors. Licence: MIT. https://github.com/dotnet/runtime')
[void]$text.AppendLine()
[void]$text.AppendLine('SQLCipher Community Edition (native encryption library, inside SQLitePCLRaw.lib.e_sqlcipher)')
[void]$text.AppendLine('  Copyright (c) 2025, ZETETIC LLC. Licence: BSD-3-Clause (text below). https://github.com/sqlcipher/sqlcipher')
[void]$text.AppendLine()

foreach ($item in $shipped) {
    [void]$text.AppendLine("$($item.Id) $($item.Version)")
    $line = '  '
    $owner = if ($item.Copyright) { $item.Copyright } else { $item.Authors }
    if ($owner) { $line += $owner.TrimEnd('.', ' ') + '. ' }
    $line += 'Licence: ' + $(if ($item.LicenseId) { $item.LicenseId } else { 'see package' })
    if ($item.Url) { $line += '. ' + $item.Url }
    [void]$text.AppendLine($line)
    [void]$text.AppendLine()
}

[void]$text.AppendLine('=== Licence texts ===')

# SPDX licences, once each.
$spdx = $shipped | Where-Object { $_.LicenseId -and $_.LicenseId -notlike 'File:*' } | Select-Object -ExpandProperty LicenseId -Unique | Sort-Object
foreach ($id in $spdx) {
    $uri = "https://raw.githubusercontent.com/spdx/license-list-data/main/text/$id.txt"
    $body = (Invoke-WebRequest -Uri $uri -UseBasicParsing).Content
    if ($body -is [byte[]]) { $body = [System.Text.Encoding]::UTF8.GetString($body) }

    [void]$text.AppendLine()
    [void]$text.AppendLine("--- $id ---")
    [void]$text.AppendLine()
    [void]$text.AppendLine($body.Trim())
}

# Licences that are files inside packages, once per distinct file content.
$files = $shipped | Where-Object { $_.LicenseFile } | Group-Object LicenseId
foreach ($group in $files) {
    $first = $group | Select-Object -ExpandProperty Group | Select-Object -First 1
    $names = ($group.Group | Select-Object -ExpandProperty Id) -join ', '

    [void]$text.AppendLine()
    [void]$text.AppendLine("--- Licence supplied with: $names ---")
    [void]$text.AppendLine()
    [void]$text.AppendLine((Get-Content $first.LicenseFile -Raw).Trim())
}

[void]$text.AppendLine()
[void]$text.AppendLine('--- SQLCipher (BSD-3-Clause) ---')
[void]$text.AppendLine()
[void]$text.AppendLine($sqlCipherLicense.Trim())

Set-Content -Path $output -Value $text.ToString() -Encoding UTF8
Write-Host "Wrote $output ($($shipped.Count) packages, $($spdx.Count) SPDX licences, $($files.Count) licence files)."
