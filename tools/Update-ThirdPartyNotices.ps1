<#
.SYNOPSIS
    Regenerates THIRD-PARTY-NOTICES.txt from the packages the app really ships.

.DESCRIPTION
    Reads the restore result of the app project (src/EasyTax.App/obj/project.assets.json, so build or restore first), keeps
    the packages that put files into the app (not build tools), and writes each package with its copyright and licence, followed
    by the licence texts. Run it whenever a package is added, removed or updated, then commit the result.

    Licence texts for SPDX identifiers (MIT, Apache-2.0) are downloaded from the SPDX licence list; licences that ship as a file
    inside a package (the Microsoft ones) are read from the package. The SQLCipher text is below because SQLCipher is bundled
    inside SQLitePCLRaw.lib.e_sqlcipher and has no entry of its own.
#>
[CmdletBinding()]
param()

$ErrorActionPreference = 'Stop'

$root = Split-Path -Parent $PSScriptRoot
$assetsPath = Join-Path $root 'src/EasyTax.App/obj/project.assets.json'
$output = Join-Path $root 'THIRD-PARTY-NOTICES.txt'
$packages = Join-Path $env:USERPROFILE '.nuget/packages'

if (-not (Test-Path $assetsPath)) {
    throw "Missing $assetsPath. Run 'dotnet build EasyTax.slnx' first."
}

$sqlCipherLicense = @'
