using System.Collections.ObjectModel;
using System.Reflection;
using CommunityToolkit.Mvvm.ComponentModel;
using CommunityToolkit.Mvvm.Input;
using EasyTax.App.Backups;
using EasyTax.App.Localization;
using EasyTax.App.Security;
using EasyTax.App.Shell;
using EasyTax.Core.Domain.Years;
using Windows.ApplicationModel.DataTransfer;

namespace EasyTax.App.Settings;

public sealed partial class SettingsViewModel : ViewModelBase
{
	private const int FirstAllowedYear = 2000;
	private const int LastAllowedYear = 2100;

	private readonly ISettingsService _settings;
	private readonly IAccountingYearRepository _yearRepository;
	private readonly IClientContext _context;
	private readonly IToastService _toasts;
	private readonly ILocalizer _localizer;
	private readonly IDialogService _dialogs;
	private readonly DatabaseKeyService _keys;
	private readonly BackupManager _backups;
	private readonly RestoreCoordinator _restore;
	private readonly IPickerService _pickers;

	public SettingsViewModel(ISettingsService settings, ILocalizer localizer, IAccountingYearRepository yearRepository, IClientContext context, IToastService toasts, IDialogService dialogs, DatabaseKeyService keys, BackupManager backups, RestoreCoordinator restore, IPickerService pickers)
	{
		_settings = settings;
		_yearRepository = yearRepository;
		_context = context;
		_toasts = toasts;
		_localizer = localizer;
		_dialogs = dialogs;
		_keys = keys;
		_backups = backups;
		_restore = restore;
		_pickers = pickers;

		ScheduledBackups = settings.Current.ScheduledBackups;
		BackupFolder = backups.Folder;
		RefreshBackupStatus();

		ThemeOptions =
		[
			new(AppTheme.System, localizer["Theme_System"]),
			new(AppTheme.Light, localizer["Theme_Light"]),
			new(AppTheme.Dark, localizer["Theme_Dark"]),
		];
		SelectedTheme = ThemeOptions.First(o => o.Value == settings.Current.Theme);
		NewYear = DateTime.Today.Year;

		AppVersion = Assembly.GetExecutingAssembly().GetName().Version?.ToString(3) ?? "?";
	}

	public IReadOnlyList<ThemeOption> ThemeOptions { get; }

	public string AppVersion { get; }

	/// <summary>The years the app offers, ascending. A year with data cannot be removed.</summary>
	public ObservableCollection<YearItem> Years { get; } = [];

	[ObservableProperty]
	public partial ThemeOption SelectedTheme { get; set; }

	/// <summary>Value of the "new year" box (NaN while it is empty).</summary>
	[ObservableProperty]
	[NotifyCanExecuteChangedFor(nameof(AddYearCommand))]
	public partial double NewYear { get; set; }

	/// <summary>The folder backups are written to.</summary>
	[ObservableProperty]
	public partial string BackupFolder { get; set; } = string.Empty;

	[ObservableProperty]
	public partial bool ScheduledBackups { get; set; }

	/// <summary>"Last backup: ..." or "no backups in this folder".</summary>
	[ObservableProperty]
	public partial string BackupStatus { get; set; } = string.Empty;

	/// <summary>True while a backup or restore runs, so the buttons cannot be pressed twice.</summary>
	[ObservableProperty]
	[NotifyCanExecuteChangedFor(nameof(BackupNowCommand), nameof(RestoreCommand))]
	public partial bool IsBackupBusy { get; set; }

	partial void OnScheduledBackupsChanged(bool value)
		=> _settings.Update(s => s with { ScheduledBackups = value });

	partial void OnSelectedThemeChanged(ThemeOption value)
		=> _settings.Update(s => s with { Theme = value.Value });

	public override Task OnNavigatedToAsync(object? parameter)
	{
		_backups.Finished += OnBackupFinished;
		RefreshBackupStatus();

		return LoadYearsAsync();
	}

	public override void OnNavigatedFrom() => _backups.Finished -= OnBackupFinished;

	private bool CanAddYear() => !double.IsNaN(NewYear) && NewYear is >= FirstAllowedYear and <= LastAllowedYear && Years.All(y => y.Year != (int)NewYear);

	/// <summary>Shows the recovery key again. The user is already inside the app, so nothing is asked first.</summary>
	[RelayCommand]
	private async Task ShowRecoveryKeyAsync()
	{
		var key = _keys.TryLoad();
		if (key is null)
			return;

		var formatted = DatabaseKeyService.Format(key);
		var copy = await _dialogs.ConfirmAsync(
			_localizer["Settings_Key_Title"],
			[new DialogText(_localizer["Settings_Key_Message"]), new DialogText(formatted, IsBold: true)],
			_localizer["Settings_Key_Copy"],
			_localizer["Settings_Key_Close"]);

		if (!copy)
			return;

		var package = new DataPackage();
		package.SetText(formatted);
		Clipboard.SetContent(package);
		_toasts.Success(_localizer["Toast_KeyCopied"]);
	}

	/// <summary>Shows the licences of the components the app is built from (the file generated by tools/Update-ThirdPartyNotices.ps1).</summary>
	[RelayCommand]
	private async Task ShowLicensesAsync()
	{
		var path = Path.Combine(AppContext.BaseDirectory, "THIRD-PARTY-NOTICES.txt");
		if (!File.Exists(path))
			return;

		var text = await File.ReadAllTextAsync(path);
		await _dialogs.ShowTextAsync(_localizer["Settings_Licenses_Title"], text, _localizer["Settings_Licenses_Close"]);
	}

	[RelayCommand]
	private async Task BrowseBackupFolderAsync()
	{
		var folder = await _pickers.PickFolderAsync();
		if (folder is null)
			return;

		_settings.Update(s => s with { BackupFolder = folder });
		BackupFolder = _backups.Folder;
		RefreshBackupStatus();

		// The new folder gets the full deletion history, so it protects restores like the old one did.
		await _backups.SyncDeletionLogAsync();
	}

	[RelayCommand(CanExecute = nameof(CanUseBackups))]
	private async Task BackupNowAsync()
	{
		IsBackupBusy = true;
		try
		{
			await _backups.RunNowAsync();
		}
		finally
		{
			IsBackupBusy = false;
		}
	}

	[RelayCommand(CanExecute = nameof(CanUseBackups))]
	private async Task RestoreAsync()
	{
		IsBackupBusy = true;
		try
		{
			await _restore.RestoreAsync();
		}
		finally
		{
			IsBackupBusy = false;
		}
	}

	private bool CanUseBackups() => !IsBackupBusy;

	private void OnBackupFinished(object? sender, EventArgs e) => RefreshBackupStatus();

	private void RefreshBackupStatus()
	{
		var latest = _backups.Latest();
		BackupStatus = latest is null
			? _localizer["Backup_None"]
			: string.Format(System.Globalization.CultureInfo.CurrentCulture, _localizer["Backup_Last"], latest.Manifest.CreatedAt.LocalDateTime.ToString("g", System.Globalization.CultureInfo.CurrentCulture));
	}

	[RelayCommand(CanExecute = nameof(CanAddYear))]
	private async Task AddYearAsync()
	{
		var year = (int)NewYear;
		if (!await _yearRepository.AddAsync(year))
			return;

		await ReloadYearsEverywhereAsync();
		_toasts.Success(string.Format(System.Globalization.CultureInfo.CurrentCulture, _localizer["Toast_YearAdded"], year));
	}

	[RelayCommand]
	private async Task RemoveYearAsync(int year)
	{
		if (!await _yearRepository.TryRemoveAsync(year))
			return;

		await ReloadYearsEverywhereAsync();
		_toasts.Success(string.Format(System.Globalization.CultureInfo.CurrentCulture, _localizer["Toast_YearRemoved"], year));
	}

	// The app bar and dashboard read the years from the shared context, so it has to reload too.
	private async Task ReloadYearsEverywhereAsync()
	{
		await _context.ReloadAsync();
		await LoadYearsAsync();
	}

	private async Task LoadYearsAsync()
	{
		var years = await _yearRepository.GetAllAsync();

		var items = new List<YearItem>();
		foreach (var year in years)
			items.Add(new YearItem(year.Year, await _yearRepository.HasDataAsync(year.Year)));

		Years.Clear();
		foreach (var item in items)
			Years.Add(item);

		AddYearCommand.NotifyCanExecuteChanged();
	}
}

public sealed record ThemeOption(AppTheme Value, string Label);

public sealed record YearItem(int Year, bool HasData)
{
	public bool CanRemove => !HasData;
}
